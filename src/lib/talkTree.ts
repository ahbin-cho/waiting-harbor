/** 같은 날, 같은 마디, 같은 차례면 같은 말. 최근에 한 말은 피해요. */
export function lineOf(nodeId: string, sp: Speaker, seed: number, recent: string[] = []) {
  const node = TREE[nodeId] ?? TREE.menu;
  const own = sp.isPet ? (node.bySpecies?.[sp.species ?? ""] ?? []) : [];
  const base = sp.isPet ? node.pet : node.person;
  // 종류별 말이 있으면 그 말과 기본 말을 섞어서
  const pool = [...own, ...own, ...base];
  const fresh = pool.filter((x) => !recent.includes(x));
  const list = fresh.length ? fresh : pool;
  let h = seed >>> 0;
  for (const c of nodeId) h = (Math.imul(h, 31) + c.charCodeAt(0)) >>> 0;
  return list[h % list.length];
}

export const isKeeperNode = (nodeId: string) => !!TREE[nodeId]?.keeper;

export function choicesOf(nodeId: string, sp: Speaker): Choice[] {
  const node = TREE[nodeId] ?? TREE.menu;
  return node.choices.filter((c) => !c.only || (c.only === "pet") === sp.isPet);
}
