/** 같은 말과 같은 날이면 같은 값 */
function hashOf(text: string, seed: number) {
  let h = seed >>> 0;
  for (const c of text) h = (Math.imul(h, 31) + c.charCodeAt(0)) >>> 0;
  return h;
}

/**
 * AI 없이 고르는 답장. 내가 한 말의 주제를 알아듣고 맞는 말을 골라요.
 * recent: 바로 전에 했던 답장들 (되풀이하지 않게)
 */
export function templateReply(w: Who, text: string, seed: number, recent: string[] = []) {
  if (isDanger(text)) return SAFETY_REPLY;
  const h = hashOf(text, seed);
  const fresh = (list: string[]) => {
    const left = list.filter((x) => !recent.some((r) => r.includes(x)));
    const pool = left.length ? left : list;
    return pool[h % pool.length];
  };
  const t = text.replace(/\s+/g, " ");
  const hits = TOPICS.filter((tp) => tp.keys.some((k) => t.includes(k)));
  let main: string;
  if (hits.length) {
    // 여러 주제가 겹치면 앞의 것(더 마음이 실린 주제)부터
    const tp = hits[0];
    main = fresh(w.isPet ? tp.pet : tp.person);
  } else {
    main = fresh(w.isPet ? (PET_DEFAULT[w.species ?? ""] ?? PET_ANY) : PERSON_DEFAULT);
  }
  // 덧붙이는 말은 가끔만, 그리고 최근에 붙였던 말은 다시 붙이지 않아요
  const close = (w.isPet ? PET_CLOSE : PERSON_CLOSE)[(h >>> 3) % 5];
  const usedClose = close && recent.some((r) => r.endsWith(close));
  return close && !usedClose && !main.includes(close) ? `${main} ${close}` : main;
}
